public class MeritsAndDemerits {
    public static void main(String[] args) {
        System.out.println("Merits:");
        System.out.println("1. Reusability");
        System.out.println("2. Modularity");
        System.out.println("3. Maintainability");
        System.out.println("4. Data organization");

        System.out.println("Demerits:");
        System.out.println("1. More design overhead for small programs");
        System.out.println("2. Additional memory and runtime overhead in some designs");
        System.out.println("3. Can become complex when object relationships grow");
    }
}
